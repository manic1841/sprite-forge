/**
 * `reproduce` — the cross-cutting reproducibility and validity contract.
 *
 * A committed Asset is a **baked snapshot**: the stored `sheet.png` is
 * authoritative and re-running does not replace it (ADR-0004, docs/architecture.md
 * "Reproducibility"). Deterministic stages are re-runnable from the **provenance**
 * sidecar — Recording + Segment snapshot + background settings + Repair-script
 * reference + placement offset — and must land on identical bytes.
 *
 * `verifyReproducible` re-runs a stage from stored provenance **without writing
 * anything**, compares its output to the committed artifacts byte for byte, and
 * reports any divergence. Provenance-only fields that legitimately change between
 * runs (the Manifest's `lock.exportedAt`) are excluded and named in the report; a
 * field that is *stored* rather than derivable (a Clip's `loop` flag) is likewise
 * authoritative and named as excluded.
 */

import { readClip, readSequence, renderSequenceSheet, tileRepairedFrames } from './assets.js';
import { renderSegmentFrames } from './draft.js';
import { StoreError } from './errors.js';
import { buildExport, readExportManifest, type ExportManifest } from './export.js';
import { assertValidId } from './ids.js';
import { assetMetaPath, canvasPath, manifestPath, sheetPath } from './layout.js';
import { readRepairScript } from './repair.js';
import { pathExists, readBinaryFile, readJsonFile } from './store/index.js';
import type { Canvas } from './character.js';
import { validateArtifact } from './validate.js';

/** What `verifyReproducible` re-runs. */
export type ReproducibleKind = 'clip' | 'sequence' | 'export';

/** One artifact (or field) that did not reproduce. */
export interface ReproducibilityMismatch {
  /** Store-relative path, optionally `#<field>` for a derived non-file value. */
  artifact: string;
  /** What differed between the re-run and the stored artifact. */
  detail: string;
}

/** The result of {@link verifyReproducible}. */
export interface ReproducibilityReport {
  kind: ReproducibleKind;
  /** The committed Asset id, or the Export target. */
  id: string;
  /** True when every compared artifact reproduced exactly. */
  reproducible: boolean;
  /** Store-relative paths that were compared. */
  artifacts: string[];
  /**
   * Fields deliberately excluded from the comparison: volatile provenance (an
   * Export's `lock.exportedAt`) or stored-not-derivable state (a Clip's `loop`).
   */
  excluded: string[];
  /** The artifacts that differed; empty when `reproducible` is true. */
  mismatches: ReproducibilityMismatch[];
}

/** Inputs for {@link verifyReproducible}. */
export interface VerifyReproducibleOptions {
  /** The Character that owns the Asset (also named in an Export's manifest). */
  characterId: string;
  kind: ReproducibleKind;
  /** The committed Asset id, or the Export target for `kind: 'export'`. */
  id: string;
}

/**
 * Re-run a committed stage from its stored provenance and check it lands on the
 * same bytes.
 *
 * Read-only: it never writes to the store, so it can be run at any time to assert
 * the reproducibility contract (and the baked-snapshot guarantee — a committed
 * `sheet.png` is compared against, never overwritten).
 */
export async function verifyReproducible(
  root: string,
  options: VerifyReproducibleOptions,
): Promise<ReproducibilityReport> {
  const { characterId, kind, id } = options;
  assertValidId(characterId, 'character', 'characterId');
  assertValidId(id, kind === 'export' ? 'target' : 'asset', 'id');

  switch (kind) {
    case 'clip':
      return verifyClip(root, characterId, id);
    case 'sequence':
      return verifySequence(root, characterId, id);
    case 'export':
      return verifyExport(root, characterId, id);
  }
}

/** Accumulates a report as artifacts are compared. */
interface ReportDraft {
  artifacts: string[];
  excluded: string[];
  mismatches: ReproducibilityMismatch[];
}

function newDraft(): ReportDraft {
  return { artifacts: [], excluded: [], mismatches: [] };
}

function finish(kind: ReproducibleKind, id: string, draft: ReportDraft): ReproducibilityReport {
  return {
    kind,
    id,
    reproducible: draft.mismatches.length === 0,
    artifacts: draft.artifacts,
    excluded: draft.excluded,
    mismatches: draft.mismatches,
  };
}

/** Compare re-run bytes to the stored artifact, recording a mismatch on divergence. */
function compareBytes(
  draft: ReportDraft,
  artifact: string,
  stored: Buffer,
  regenerated: Buffer,
): void {
  draft.artifacts.push(artifact);
  if (!stored.equals(regenerated)) {
    draft.mismatches.push({
      artifact,
      detail: `regenerated bytes differ from the stored artifact (${stored.length} vs ${regenerated.length} bytes)`,
    });
  }
}

/** Compare a derived value to the stored one, recording a mismatch on divergence. */
function compareValue(
  draft: ReportDraft,
  artifact: string,
  stored: unknown,
  derived: unknown,
): void {
  draft.artifacts.push(artifact);
  if (canonical(stored) !== canonical(derived)) {
    draft.mismatches.push({
      artifact,
      detail: `stored ${canonical(stored)} does not match the derived ${canonical(derived)}`,
    });
  }
}

/** A stable JSON rendering (object keys sorted) for value comparison. */
function canonical(value: unknown): string {
  return JSON.stringify(sortKeys(value));
}

function sortKeys(value: unknown): unknown {
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const key of Object.keys(value as Record<string, unknown>).sort()) {
      out[key] = sortKeys((value as Record<string, unknown>)[key]);
    }
    return out;
  }
  return value;
}

/** Re-run a committed Clip from provenance and compare its sheet and derived meta. */
async function verifyClip(
  root: string,
  characterId: string,
  clipId: string,
): Promise<ReproducibilityReport> {
  const canvas = await readCanvas(root, characterId);
  const clip = await readClip(root, { characterId, clipId });
  const { meta, provenance } = clip;
  const draft = newDraft();

  // Re-run stages 1-4 from the provenance snapshot alone. The recorded background
  // colour is used directly (keying by the same colour yields the same pixels),
  // and the source must still hash to the recorded value.
  const rendered = await renderSegmentFrames(root, {
    recordingId: provenance.recordingId,
    segment: provenance.segment,
    canvas,
    background: provenance.background.hex,
    tolerance: provenance.background.tolerance,
    expectedHash: provenance.recordingHash,
  });

  // Replay the stored Repair script (never re-derived), then bake with the offset.
  const script = provenance.repair
    ? await readRepairScript(root, { characterId, clipId })
    : { operations: [] };
  const sheet = await tileRepairedFrames(
    rendered.frames,
    canvas,
    script,
    provenance.placementOffset ?? { x: 0, y: 0 },
  );

  const sheetRel = sheetPath(characterId, 'clip', clipId);
  compareBytes(draft, sheetRel, await readBinaryFile(root, sheetRel), sheet);

  // frameCount and delaysMs derive deterministically from the Recording + Segment.
  const metaRel = assetMetaPath(characterId, 'clip', clipId);
  compareValue(draft, `${metaRel}#frameCount`, meta.frameCount, rendered.frames.length);
  compareValue(draft, `${metaRel}#delaysMs`, meta.delaysMs, rendered.delaysMs);
  // `loop` is a stored choice, not derivable from provenance: authoritative.
  draft.excluded.push(`${metaRel}#loop`);

  return finish('clip', clipId, draft);
}

/** Re-run a committed Sequence from provenance and compare its sheet and derived meta. */
async function verifySequence(
  root: string,
  characterId: string,
  sequenceId: string,
): Promise<ReproducibilityReport> {
  const canvas = await readCanvas(root, characterId);
  const sequence = await readSequence(root, { characterId, sequenceId });
  const draft = newDraft();

  // Clips are immutable, so re-concatenating from provenance is deterministic.
  const { sheet, meta: derived } = await renderSequenceSheet(root, {
    characterId,
    sequenceId,
    canvas,
  });

  const sheetRel = sheetPath(characterId, 'sequence', sequenceId);
  compareBytes(draft, sheetRel, await readBinaryFile(root, sheetRel), sheet);

  const metaRel = assetMetaPath(characterId, 'sequence', sequenceId);
  compareValue(draft, `${metaRel}#frameCount`, sequence.meta.frameCount, derived.frameCount);
  compareValue(draft, `${metaRel}#delaysMs`, sequence.meta.delaysMs, derived.delaysMs);
  // A Sequence always loops; `loop` is fixed, not re-derived.
  draft.excluded.push(`${metaRel}#loop`);

  return finish('sequence', sequenceId, draft);
}

/**
 * Re-run an Export from its Manifest's own consumer inputs and compare the bundle.
 *
 * The copied sheets are re-generated from the committed Assets (the baked
 * snapshot), and the Manifest is rebuilt and compared with the volatile
 * `lock.exportedAt` timestamp excluded — it is provenance, not pixels.
 */
async function verifyExport(
  root: string,
  characterId: string,
  target: string,
): Promise<ReproducibilityReport> {
  const stored = await readExportManifest(root, target);
  const { manifest } = stored;
  if (manifest.character !== characterId) {
    throw new StoreError(
      `Export "${target}" is for Character "${manifest.character}", not "${characterId}".`,
    );
  }
  const draft = newDraft();

  const rebuilt = await buildExport(root, {
    characterId,
    target,
    animations: Object.keys(manifest.animations),
    bindings: manifest.bindings,
    situations: Object.keys(manifest.bindings),
    flipsFacing: Object.entries(manifest.animations)
      .filter(([, animation]) => animation.flipsFacing)
      .map(([id]) => id),
    authoredFacing: manifest.authoredFacing,
    formatVersion: manifest.formatVersion,
  });

  const manifestRel = manifestPath(target);
  draft.excluded.push(`${manifestRel}#lock.exportedAt`);
  compareValue(draft, manifestRel, stripExportedAt(manifest), stripExportedAt(rebuilt.manifest));

  for (const sheet of rebuilt.sheets) {
    compareBytes(draft, sheet.relPath, await readBinaryFile(root, sheet.relPath), sheet.data);
  }

  return finish('export', target, draft);
}

/** A copy of the Manifest with the volatile `lock.exportedAt` removed for comparison. */
function stripExportedAt(manifest: ExportManifest): ExportManifest {
  const copy = structuredClone(manifest);
  delete (copy.lock as { exportedAt?: string }).exportedAt;
  return copy;
}

/** Read and validate a Character's Canvas. */
async function readCanvas(root: string, characterId: string): Promise<Canvas> {
  const artifactPath = canvasPath(characterId);
  if (!(await pathExists(root, artifactPath))) {
    throw new StoreError(
      `No Character "${characterId}" in the store (${artifactPath} is missing).`,
    );
  }
  const value = await readJsonFile(root, artifactPath);
  validateArtifact('canvas', value, { artifact: artifactPath });
  return value as Canvas;
}

